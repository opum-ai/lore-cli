describe("lore scaffold mkdocs — never-silent-clobber (AC: user-owned, never re-overwritten)", () => {
  test("a re-run without --force refuses with a conflict (exit 5) and touches nothing", () => {
    scaffold(["mkdocs"]);
    const yamlBefore = readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8");
    const tagsBefore = readFileSync(join(root, TAGS_INDEX_REL_PATH), "utf8");

    const err = expectError("conflict", () =>
      runScaffold({ root, output: JSON_CTX, args: ["mkdocs"], stdout: capture() }),
    );
    expect(err.message).toContain(MKDOCS_CONFIG_REL_PATH);
    expect(err.message).toContain(TAGS_INDEX_REL_PATH);
    expect(err.hint).toContain("--force");
    expect(readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8")).toBe(yamlBefore);
    expect(readFileSync(join(root, TAGS_INDEX_REL_PATH), "utf8")).toBe(tagsBefore);
  });

  test("a hand-authored mkdocs.yml alone (tags.md absent) still refuses without --force", () => {
    writeFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "site_name: hand-authored\n");
    const err = expectError("conflict", () =>
      runScaffold({ root, output: JSON_CTX, args: ["mkdocs"], stdout: capture() }),
    );
    expect(err.input).toMatchObject({ paths: [MKDOCS_CONFIG_REL_PATH] });
    expect(readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8")).toBe("site_name: hand-authored\n");
    expect(existsSync(join(root, TAGS_INDEX_REL_PATH))).toBe(false);
  });

  test("--force overwrites both existing files and reports `updated`", () => {
    scaffold(["mkdocs"]);
    const { code, result } = scaffold(["mkdocs", "--force"]);
    expect(code).toBe(0);
    expect(result.force).toBe(true);
    expect(result.files).toEqual([
      { path: MKDOCS_CONFIG_REL_PATH, action: "updated" },
      { path: TAGS_INDEX_REL_PATH, action: "updated" },
    ]);
  });

  test("--force on a fresh repo still reports `created` (not `updated`)", () => {
    const { result } = scaffold(["mkdocs", "--force"]);
    expect(result.files.every((f) => f.action === "created")).toBe(true);
  });

  // POSIX-only: a read-only directory doesn't reliably block a write on Windows the same way.
  test.skipIf(process.platform === "win32")(
    "a write failure partway through the plan rolls back the earlier file (true all-or-nothing)",
    () => {
      // Regression: the write loop used to leave mkdocs.yml (planned first) behind on disk when
      // the docs/tags.md write failed, contradicting the documented all-or-nothing guarantee.
      mkdirSync(join(root, "docs"), { recursive: true, mode: 0o555 });
      try {
        const err = expectError("denied", () =>
          runScaffold({ root, output: JSON_CTX, args: ["mkdocs"], stdout: capture() }),
        );
        expect(err.type).toBe("denied");
        expect(existsSync(join(root, MKDOCS_CONFIG_REL_PATH))).toBe(false);
      } finally {
        chmodSync(join(root, "docs"), 0o755);
        rmSync(join(root, "docs"), { recursive: true, force: true });
      }
    },
  );

  test("--force run's rollback restores the PREVIOUS bytes of an already-overwritten file, not just a delete", () => {
    scaffold(["mkdocs"]);
    const yamlBefore = readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8");
    // Make the SECOND planned write (docs/tags.md) fail after the FIRST (mkdocs.yml) succeeds,
    // by replacing tags.md with a directory (a write there throws EISDIR).
    rmSync(join(root, TAGS_INDEX_REL_PATH));
    mkdirSync(join(root, TAGS_INDEX_REL_PATH));
    expectError("conflict", () =>
      runScaffold({ root, output: JSON_CTX, args: ["mkdocs", "--force"], stdout: capture() }),
    );
    expect(readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8")).toBe(yamlBefore);
  });

  test("a pre-existing file that is writable but unreadable is never deleted by a rollback (review #1)", () => {
    if (process.getuid?.() === 0) {
      return; // root bypasses read-permission checks, so this repro can't be set up
    }
    writeFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "site_name: original\n");
    chmodSync(join(root, MKDOCS_CONFIG_REL_PATH), 0o200); // write-only: unreadable, even by the owner
    let unreadable = false;
    try {
      readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8");
    } catch {
      unreadable = true;
    }
    if (!unreadable) {
      chmodSync(join(root, MKDOCS_CONFIG_REL_PATH), 0o644);
      return; // environment ignores the mode (e.g. a permissive filesystem) — skip
    }
    // A later planned write is ALSO forced to fail, mirroring the original bug's repro shape
    // (the pre-fix rollback only manifested once some later step threw); the fix must refuse
    // outright before ever reaching this, but the forced failure is left in place regardless so
    // the assertion below holds under either fix strategy.
    mkdirSync(join(root, TAGS_INDEX_REL_PATH), { recursive: true });
    let thrown: unknown;
    try {
      runScaffold({ root, output: JSON_CTX, args: ["mkdocs", "--force"], stdout: capture() });
    } catch (err) {
      thrown = err;
    } finally {
      chmodSync(join(root, MKDOCS_CONFIG_REL_PATH), 0o644); // restore so afterEach's rmSync can clean up
    }
    expect(thrown).toBeInstanceOf(LoreError);
    expect((thrown as LoreError).type).toBe("denied");
    // Regression: the old rollback used `before === undefined` to mean "delete on rollback" — true
    // both when a file never existed AND when it existed but couldn't be read — so this
    // pre-existing, merely-unreadable file used to get DELETED by the rollback triggered by the
    // later (docs/tags.md) failure. A file that existed before the command ran must never be
    // touched, let alone deleted.
    expect(existsSync(join(root, MKDOCS_CONFIG_REL_PATH))).toBe(true);
    expect(readFileSync(join(root, MKDOCS_CONFIG_REL_PATH), "utf8")).toBe("site_name: original\n");
  });

  test("a run against a repo with no docs/ rolls back the freshly-created directory on a later failure (review #2)", () => {
    expect(existsSync(join(root, "docs"))).toBe(false);
    // Force the FIRST planned write (mkdocs.yml, at the repo root) to fail structurally — a
    // directory sitting where the file must go — so the failure happens strictly AFTER `docs/`
    // has already been freshly created by this same run's directory-ensure step.
    mkdirSync(join(root, MKDOCS_CONFIG_REL_PATH), { recursive: true });
    const err = expectError("conflict", () =>
      runScaffold({ root, output: JSON_CTX, args: ["mkdocs", "--force"], stdout: capture() }),
    );
    expect(err.type).toBe("conflict");
    // Regression: `ensureDir(docs/, …)` used to run outside the write-loop's rollback entirely, so
    // a freshly created (and, since nothing was ever written into it, still-empty) `docs/` was left
    // behind on disk after this failure — breaking the "writes nothing on failure" contract for the
    // directory itself.
    expect(existsSync(join(root, "docs"))).toBe(false);
  });
});

describe("core/consumer-scaffold — buildDocusaurusScaffold (pure)", () => {
  test("is deterministic: identical options produce identical bytes", () => {
    const opts = { timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" };
    expect(buildDocusaurusScaffold(opts)).toEqual(buildDocusaurusScaffold(opts));
  });

  test("plans exactly website/package.json, website/docusaurus.config.js, website/sidebars.js, in that order", () => {
    const plan = buildDocusaurusScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" });
    expect(plan.dirs).toEqual(["website"]);
    expect(plan.files.map((f) => f.path)).toEqual([
      WEBSITE_PACKAGE_JSON_REL_PATH,
      DOCUSAURUS_CONFIG_REL_PATH,
      SIDEBARS_REL_PATH,
    ]);
  });

  test("docusaurus.config.js carries every documented setting, as CommonJS (consumer-compatibility.md §3.4 / ADR-0010 §2)", () => {
    const plan = buildDocusaurusScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "my-project" });
    const js = plan.files.find((f) => f.path === DOCUSAURUS_CONFIG_REL_PATH)?.contents ?? "";
    expect(js).toContain("module.exports = {");
    expect(js).not.toMatch(/^export default/m);
    expect(js).toContain('title: "my-project"');
    expect(js).toContain('format: "detect"');
    expect(js).toContain('onBrokenMarkdownLinks: "warn"');
    expect(js).toContain('onBrokenLinks: "warn"');
    expect(js).toContain('onBrokenAnchors: "warn"');
    expect(js).toContain("trailingSlash: false");
    expect(js).toContain('path: "../docs"');
    expect(js).toContain('routeBasePath: "/"');
    expect(js).toContain('sidebarPath: "./sidebars.js"');
    expect(js).toContain("blog: false");
  });

  test("website/package.json is valid JSON, pins Docusaurus packages in lockstep, and never sets type:module", () => {
    const plan = buildDocusaurusScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" });
    const raw = plan.files.find((f) => f.path === WEBSITE_PACKAGE_JSON_REL_PATH)?.contents ?? "";
    const pkg = JSON.parse(raw) as {
      type?: string;
      scripts: { build: string };
      dependencies: Record<string, string>;
    };
    expect(pkg.type).toBeUndefined();
    expect(pkg.scripts.build).toBe("docusaurus build");
    expect(pkg.dependencies["@docusaurus/core"]).toBe(pkg.dependencies["@docusaurus/preset-classic"]);
    expect(pkg.dependencies.react).toBeDefined();
    expect(pkg.dependencies["react-dom"]).toBeDefined();
  });

  test("sidebars.js is a fully-autogenerated CommonJS sidebar", () => {
    const plan = buildDocusaurusScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" });
    const js = plan.files.find((f) => f.path === SIDEBARS_REL_PATH)?.contents ?? "";
    expect(js).toContain("module.exports = {");
    expect(js).not.toMatch(/^export default/m);
    expect(js).toContain('type: "autogenerated"');
    expect(js).toContain('dirName: "."');
  });
});

