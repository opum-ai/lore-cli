/**
 * consumer-scaffold.test.ts — `lore scaffold mkdocs` (LORE-39) and `lore scaffold docusaurus`
 * (LORE-40): the additive MkDocs and Docusaurus consumer configs.
 *
 * AC#1 ("build succeeds on the bundle") is exercised end-to-end by the `scaffold-mkdocs` and
 * `scaffold-docusaurus` CI jobs (a real `mkdocs build` / `docusaurus build` against the
 * scaffolded config + this repo's own bundle) — real Python/MkDocs and Node/Docusaurus
 * toolchains are deliberately not `bun test` dependencies (matching the "compile smoke" job's
 * separation for `bun build --compile`). This suite pins the generated bytes and exercises the
 * command's own contract: never-silent-clobber (exit 5 without `--force`), the all-or-nothing
 * pre-flight, and argument validation. Docusaurus's rollback/pre-flight edge cases (read-only
 * dir, unreadable pre-existing file, a freshly-ensured directory rolled back on a later
 * failure, etc.) are not re-tested per target — both targets share the exact same
 * `writeAllOrRollback` primitive, already exercised exhaustively by the mkdocs suite below.
 */

import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { load as yamlLoad } from "js-yaml";
import { runScaffold, type ScaffoldResult } from "../src/commands/scaffold";
import { parseConcept } from "../src/core/concept";
import {
  buildDocusaurusScaffold,
  buildMkdocsScaffold,
  DOCUSAURUS_CONFIG_REL_PATH,
  MKDOCS_CONFIG_REL_PATH,
  SIDEBARS_REL_PATH,
  TAGS_INDEX_REL_PATH,
  WEBSITE_PACKAGE_JSON_REL_PATH,
} from "../src/core/consumer-scaffold";
import { LoreError } from "../src/errors";
import type { OutputContext } from "../src/output";
import { capture, expectError } from "./helpers";

const JSON_CTX: OutputContext = { mode: "json", color: false };
const PLAIN_CTX: OutputContext = { mode: "plain", color: false };
const FIXED_CLOCK = (): Date => new Date("2026-07-11T12:00:00Z");

let root: string;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "lore-scaffold-"));
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

/** Run `scaffold` in JSON mode and return the parsed `data` payload plus the exit code. */
function scaffold(args: string[]): { code: number; result: ScaffoldResult } {
  const stdout = capture();
  const code = runScaffold({ root, output: JSON_CTX, args, stdout, clock: FIXED_CLOCK });
  const envelope = JSON.parse(stdout.text()) as { kind: string; data: ScaffoldResult };
  expect(envelope.kind).toBe("scaffold.result");
  return { code, result: envelope.data };
}

describe("core/consumer-scaffold — buildMkdocsScaffold (pure)", () => {
  test("is deterministic: identical options produce identical bytes", () => {
    const opts = { timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" };
    expect(buildMkdocsScaffold(opts)).toEqual(buildMkdocsScaffold(opts));
  });

  test("plans exactly mkdocs.yml (repo root) and docs/tags.md, in that order", () => {
    const plan = buildMkdocsScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" });
    expect(plan.files.map((f) => f.path)).toEqual([MKDOCS_CONFIG_REL_PATH, TAGS_INDEX_REL_PATH]);
  });

  test("mkdocs.yml carries every documented setting (consumer-compatibility.md §3.3 / ADR-0010 §2)", () => {
    const plan = buildMkdocsScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "my-project" });
    const yaml = plan.files.find((f) => f.path === MKDOCS_CONFIG_REL_PATH)?.contents ?? "";
    expect(yaml).toContain('site_name: "my-project"');
    expect(yaml).toContain("docs_dir: docs");
    expect(yaml).toContain("name: material");
    expect(yaml).toContain("navigation.indexes");
    expect(yaml).toContain("- search");
    expect(yaml).toContain("- tags");
    expect(yaml).toContain("strict: false");
    expect(yaml).toContain("absolute_links: relative_to_docs");
    expect(yaml).toContain("not_found: warn");
    expect(yaml).toContain("anchors: warn");
    expect(yaml).toContain("omitted_files: ignore");
    expect(yaml).toContain("not_in_nav: |\n  /log.md");
  });

  test("site_name is always double-quoted, so a YAML-1.1 boolean/null/numeric-looking directory name is never type-coerced", () => {
    // Regression: an earlier "quote only if unsafe" heuristic's blocklist covered only
    // true/false/null/~, missing the wider YAML 1.1 core-schema literals (yes/no/on/off/y/n,
    // case-insensitive) a PyYAML-based loader (mkdocs') resolves as booleans — a repo directory
    // named e.g. "off" would silently become a bool, failing mkdocs' `site_name: str` requirement
    // despite `lore scaffold mkdocs` reporting success. Always double-quoting removes the whole
    // class of YAML-implicit-typing surprises rather than trying to enumerate them.
    for (const siteName of ["off", "Off", "no", "yes", "on", "y", "n", "2026", "null", "~", "true-ish"]) {
      const plan = buildMkdocsScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName });
      const yaml = plan.files.find((f) => f.path === MKDOCS_CONFIG_REL_PATH)?.contents ?? "";
      const parsed = yamlLoad(yaml) as { site_name: unknown };
      expect(parsed.site_name).toBe(siteName);
      expect(typeof parsed.site_name).toBe("string");
    }
  });

  test("docs/tags.md is a valid OKF Reference concept carrying the Material tags marker", () => {
    const plan = buildMkdocsScaffold({ timestamp: "2026-07-11T12:00:00.000Z", siteName: "lore" });
    const raw = plan.files.find((f) => f.path === TAGS_INDEX_REL_PATH)?.contents ?? "";
    const concept = parseConcept(TAGS_INDEX_REL_PATH, raw);
    expect(concept.type).toBe("Reference");
    expect(concept.frontmatter.title).toBe("Tags");
    expect(raw).toContain("<!-- material/tags -->");
  });

  test("stamps docs/tags.md's timestamp from the given option", () => {
    const plan = buildMkdocsScaffold({ timestamp: "2026-01-02T03:04:05.000Z", siteName: "lore" });
    const raw = plan.files.find((f) => f.path === TAGS_INDEX_REL_PATH)?.contents ?? "";
    expect(raw).toContain("timestamp: 2026-01-02T03:04:05.000Z");
  });
});

